import fs from "node:fs";
import path from "node:path";

const assetsDir = "./assets/images/emoji";
const files = fs
  .readdirSync(assetsDir)
  .filter((name) => name.endsWith(".png"))
  .map((name) => {
    const key = path.basename(name, ".png"); // 😀 → 😀
    return `  '${key}': require('../../assets/images/emoji/${name}'),`;
  })
  .sort(); // ソートで安定

const tsContent = `// @ts-nocheck\n// Auto-generated by emoji-gen.ts\nexport const emojis = {\n${files.join("\n")}\n} as const;\n\nexport type EmojiKey = keyof typeof emojis;\n`;

fs.writeFileSync("./lib/generated/emojis.ts", tsContent);

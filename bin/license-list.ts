// @ts-expect-error
import { scanDependencies } from "@callstack/licenses";
import fs from "node:fs";

type License = {
  id: string;
  name: string;
  content: string;
};

const licenses = scanDependencies("package.json");

const source: string[] = ["// @ts-nocheck", "// Auto-generated by license-list.ts", "export const licenses = {"];

for (const license of Object.keys(licenses)) {
  const content = licenses[license];
  source.push(
    `  "${license}": { id: "${license}", name: "${content.name}", content: \`${content.content?.replaceAll("`", "\\`")}\` },`,
  );
}

source.push("};");

fs.writeFileSync("./lib/generated/licenses.ts", source.join("\n"));
